// Turning a feed item into a markdown post draft that follows the project's post template.

export function slugify(title, max = 50) {
  const slug = title
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return slug.slice(0, max).replace(/-+$/, '') || 'untitled';
}

export function isoDay(date) {
  return date.toISOString().slice(0, 10);
}

export function draftFilename(item, number) {
  return `${String(number).padStart(2, '0')}-${slugify(item.title)}.md`;
}

export function renderDraft(item, { number, day }) {
  const published = item.published ? isoDay(item.published) : 'date unknown';
  const tags = item.categories.length ? item.categories.join(', ') : 'none';
  return `# Post ${String(number).padStart(2, '0')} — ${item.title}

Day: ${day} · Type: Meta news + opinion · Status: draft · Best on: LinkedIn, X, Threads

Source: ${item.link} (Meta Newsroom, published ${published})
Tags: ${tags}

## Text

<HOOK: one line that makes people stop scrolling>

What happened: ${item.summary}

Why it matters: <TODO — who is affected and why>

My take: <TODO — one honest opinion>

<QUESTION for readers>

Unofficial fan project, not affiliated with Meta.

## Video idea (30–60s)

<TODO>

## Notes

- Generated by meta-pulse. Only the headline, date, tags and summary come from the source. Read the full article before posting any other detail.
- Draft only. Nothing here has been published.
`;
}
